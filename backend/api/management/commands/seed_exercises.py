class Command(BaseCommand):
    help = "Seed the database with beginner-friendly exercises."

    def handle(self, *args, **options):
        created_count = 0
        updated_count = 0

        for exercise_data in EXERCISES:
            _, created = Exercise.objects.update_or_create(
                slug=exercise_data["slug"],
                defaults=exercise_data,
            )

            if created:
                created_count += 1
            else:
                updated_count += 1

        self.stdout.write(
            self.style.SUCCESS(
                f"Exercise seeding completed. "
                f"Created: {created_count}, Updated: {updated_count}"
            )
        )
